const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const server = require('./business-server.cjs');
(async () => {
  await new Promise(resolve=>server.listen(4174,'127.0.0.1',resolve));
  const browser = await chromium.launch({headless:true,channel:'msedge'});
  // Disable decorative cross-document transitions for deterministic rapid navigation.
  const context = await browser.newContext({viewport:{width:390,height:844},reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  const base='http://127.0.0.1:4174';
  const go=async hash=>{await page.goto(`${base}/business.html#${hash}`);await page.locator('.wb-main').waitFor();};
  const state=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('wemo-business-v1')));
  try {
    await page.goto(`${base}/profile.html`);
    await page.getByRole('link',{name:/Wemo Business/}).click();
    await page.getByRole('button',{name:'Explore demo business'}).click();
    await page.getByRole('heading',{name:'Ezo — courtyard kitchen'}).waitFor();
    await page.screenshot({path:'tests/business-dashboard-light.png',fullPage:true});
    for(const section of ['profile','ai','chat','listings','create','bookings','booking-settings','performance','subscription','billing','preview']) {
      await go(section);
      assert.equal(await page.locator('.wb-main').count(),1,section);
      const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
      assert.equal(overflow,false,`${section} horizontal overflow`);
    }
    await go('chat');
    await page.getByLabel('Your answer').fill('Step-free entrance and an accessible ground-floor bathroom.');
    await page.getByRole('button',{name:'Send answer'}).click();
    await page.getByLabel('Your answer').fill('Georgian seasonal dishes in a peaceful courtyard.');
    await page.getByRole('button',{name:'Send answer'}).click();
    await page.getByRole('link',{name:'Review AI information'}).waitFor();
    assert.ok((await state()).ai.accessibility.includes('Step-free'));
    assert.ok((await state()).ai.special.includes('Georgian'));
    await go('dashboard');
    await page.getByRole('button',{name:'Publish on Wemo'}).click();
    assert.equal((await state()).business.published,true);
    await go('create');
    await page.getByLabel('What are you creating?').selectOption('Event');
    await page.getByLabel('Title',{exact:true}).fill('Courtyard jazz evening');
    await page.getByLabel('Description',{exact:true}).fill('An intimate live jazz evening.');
    await page.getByLabel('Image URL',{exact:true}).fill('https://images.unsplash.com/photo-1517248135467-4c7edcad34c4');
    await page.getByLabel('Price per guest').fill('35');
    await page.getByRole('button',{name:'Save listing'}).click();
    await page.getByRole('heading',{name:'Courtyard jazz evening'}).waitFor();
    assert.equal((await state()).listings.length,2);
    await page.goto(`${base}/events.html`);
    await page.getByRole('heading',{name:'Courtyard jazz evening'}).waitFor();
    await page.goto(`${base}/search-results.html?q=Ezo`);
    await page.getByRole('heading',{name:'Ezo — courtyard kitchen'}).click();
    await page.getByRole('heading',{name:'Ezo — courtyard kitchen'}).waitFor();
    assert.ok(page.url().endsWith('#public'));
    await page.getByRole('link',{name:'Request a booking'}).first().click();
    await page.getByLabel('Your name').fill('Workflow Test Guest');
    const tomorrow=await page.evaluate(()=>WemoBusinessStore.dateAfter(1));
    await page.getByLabel('Date',{exact:true}).fill(tomorrow);
    await page.getByLabel('Time',{exact:true}).fill('19:00');
    await page.getByRole('button',{name:'Send booking request'}).click();
    await page.getByRole('heading',{name:'Your request is on its way'}).waitFor();
    assert.equal((await state()).bookings[0].customer,'Workflow Test Guest');
    await go('bookings');
    const bookingCard=page.locator('.wb-card').filter({has:page.getByRole('heading',{name:'Workflow Test Guest'})});
    await bookingCard.getByRole('button',{name:'Confirm',exact:true}).click();
    assert.equal((await state()).bookings[0].status,'Upcoming');
    await page.getByRole('button',{name:/^Upcoming/}).click();
    await bookingCard.getByRole('button',{name:'Mark complete'}).click();
    assert.equal((await state()).bookings[0].status,'Completed');
    await go('subscription');
    await page.getByRole('button',{name:'Upgrade to Pro'}).click();
    await page.getByRole('dialog').getByRole('button',{name:'Confirm',exact:true}).click();
    assert.equal((await state()).plan,'Pro');
    await go('billing');
    await page.getByLabel('Billing email').fill('owner@example.com');
    await page.getByLabel('Payment method').selectOption('Demo Visa ···· 4242');
    await page.getByRole('button',{name:'Save changes'}).click();
    const downloadPromise=page.waitForEvent('download');
    await page.getByRole('button',{name:'Download'}).click();
    const download=await downloadPromise;
    assert.match(download.suggestedFilename(),/wemo-demo-invoice/);
    await page.reload();
    assert.equal((await state()).billing.email,'owner@example.com');
    await go('dashboard');
    await page.evaluate(()=>document.documentElement.dataset.theme='dark');
    await page.screenshot({path:'tests/business-dashboard-dark.png',fullPage:true});
    await page.setViewportSize({width:320,height:740});
    for(const section of ['dashboard','profile','bookings','subscription','public']) {await go(section);assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false,`${section} 320px overflow`);}
    assert.deepEqual(errors,[]);
    console.log('PASS: Profile entry, all sections, AI interview, publish, create event, consumer discovery, booking lifecycle, subscription, billing download, persistence, 320px layout, and no browser errors.');
  } finally {await context.close();await browser.close();server.closeAllConnections();server.close();}
})().catch(e=>{console.error(e);server.closeAllConnections();server.close();process.exitCode=1;});
